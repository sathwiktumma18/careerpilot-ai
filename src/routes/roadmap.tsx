import { useState } from "react";
import { createFileRoute, Link } from "@tanstack/react-router";
import { motion } from "framer-motion";
import {
  CalendarRange,
  CheckCircle2,
  Flag,
  Map,
  RefreshCw,
  Sparkles,
  Target,
  Upload,
} from "lucide-react";
import { AppShell } from "@/components/layout/AppShell";
import { RoleGate } from "@/components/auth/RoleGate";
import { PageHeader } from "@/components/common/PageHeader";
import { EmptyState, ErrorState } from "@/components/common/EmptyState";
import { useResumeStore, useSelectedResume } from "@/lib/store";
import { roadmapService } from "@/services/api";
import type { RoadmapPlan } from "@/lib/roadmap";

export const Route = createFileRoute("/roadmap")({
  head: () => ({ meta: [{ title: "Career Roadmap AI — CareerPilot" }] }),
  component: RoadmapPage,
});

const HORIZONS = [4, 8, 12, 16, 24];

function RoadmapPage() {
  const resumes = useResumeStore((s) => s.resumes);
  const selected = useSelectedResume();
  const selectResume = useResumeStore((s) => s.selectResume);

  const analyzed = resumes.filter((r) => r.analysis.atsScore > 0);
  const activeId = selected && selected.analysis.atsScore > 0 ? selected.id : analyzed[0]?.id;

  const [role, setRole] = useState("Software Engineer");
  const [horizon, setHorizon] = useState(12);
  const [plan, setPlan] = useState<RoadmapPlan | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const generate = async () => {
    if (!role.trim() || loading) return;
    setLoading(true);
    setError(null);
    try {
      const p = await roadmapService.generate({
        resumeId: analyzed.length ? activeId : undefined,
        targetRole: role.trim(),
        horizon,
      });
      setPlan(p);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Generating the roadmap failed — try again.");
    } finally {
      setLoading(false);
    }
  };

  return (
    <RoleGate roles={["job_seeker"]} redirectTo="/dashboard">
      <AppShell>
        <PageHeader
          eyebrow="Career Roadmap AI"
          title="A plan from where you are to the role you want"
          description={
            plan
              ? `${plan.horizon}-week plan to reach ${plan.targetRole}, staged into concrete weekly milestones.`
              : "Set a target role and horizon — the plan targets the skill gaps your resume doesn't cover."
          }
          actions={
            plan ? (
              <span
                className={
                  "rounded-full px-2.5 py-1 text-xs font-medium " +
                  (plan.generatedBy === "gemini"
                    ? "bg-emerald-500/10 text-emerald-500"
                    : "bg-amber-500/10 text-amber-500")
                }
                title={
                  plan.generatedBy === "gemini"
                    ? "Generated by Gemini"
                    : "No Gemini key — generated from a template"
                }
              >
                {plan.generatedBy === "gemini" ? "AI-generated" : "Template plan"}
              </span>
            ) : undefined
          }
        />

        {analyzed.length === 0 ? (
          <EmptyState
            icon={Map}
            title="No analyzed resume yet"
            description="Upload a PDF resume and run an analysis — the roadmap targets the skills it detects, so you aren't re-taught what you know."
            action={
              <Link
                to="/resume/upload"
                className="inline-flex items-center gap-2 rounded-lg bg-[image:var(--gradient-primary)] px-4 py-2 text-sm font-medium text-white shadow-[var(--shadow-glow)]"
              >
                <Upload className="h-4 w-4" /> Upload resume
              </Link>
            }
          />
        ) : (
          <div className="mx-auto mt-6 max-w-3xl space-y-6">
            {/* --------------------------- Setup --------------------------- */}
            <div className="glass rounded-2xl p-6">
              <h2 className="flex items-center gap-2 text-base font-semibold">
                <Target className="h-4 w-4 text-primary" /> Plan setup
              </h2>
              <p className="mt-1 text-sm text-muted-foreground">
                Your roadmap targets the gaps between this resume and the role, one concrete outcome
                per week.
              </p>

              <label className="mt-5 block text-xs font-medium text-muted-foreground">Resume</label>
              <div className="mt-2 flex flex-wrap gap-2">
                {analyzed.map((r) => (
                  <button
                    key={r.id}
                    onClick={() => selectResume(r.id)}
                    className={
                      "rounded-full border px-3 py-1 text-xs transition " +
                      (r.id === activeId
                        ? "border-primary bg-primary/10 text-primary"
                        : "border-border bg-card/50 text-muted-foreground hover:text-foreground")
                    }
                  >
                    {r.fileName}
                  </button>
                ))}
              </div>

              <label className="mt-5 block text-xs font-medium text-muted-foreground">
                Target role
              </label>
              <input
                value={role}
                onChange={(e) => setRole(e.target.value)}
                placeholder="e.g. Senior Full Stack Engineer"
                className="mt-2 w-full rounded-xl border border-border bg-card/50 px-3 py-2 text-sm outline-none transition placeholder:text-muted-foreground/60 focus:border-primary/50 focus:ring-2 focus:ring-primary/20"
              />

              <label className="mt-5 block text-xs font-medium text-muted-foreground">
                Horizon (weeks)
              </label>
              <div className="mt-2 flex gap-2">
                {HORIZONS.map((h) => (
                  <button
                    key={h}
                    onClick={() => setHorizon(h)}
                    className={
                      "h-10 rounded-xl border px-4 text-sm font-medium transition " +
                      (horizon === h
                        ? "border-primary bg-primary/10 text-primary"
                        : "border-border bg-card/50 text-muted-foreground hover:text-foreground")
                    }
                  >
                    {h}
                  </button>
                ))}
              </div>

              <button
                onClick={() => void generate()}
                disabled={loading || !role.trim()}
                className="mt-6 inline-flex w-full items-center justify-center gap-2 rounded-lg bg-[image:var(--gradient-primary)] px-4 py-2.5 text-sm font-medium text-white shadow-[var(--shadow-glow)] transition hover:opacity-90 disabled:cursor-not-allowed disabled:opacity-50"
              >
                {loading ? (
                  <RefreshCw className="h-4 w-4 animate-spin" />
                ) : (
                  <Sparkles className="h-4 w-4" />
                )}
                {loading ? "Mapping your path…" : plan ? "Regenerate roadmap" : "Generate roadmap"}
              </button>
              {error && (
                <div className="mt-4">
                  <ErrorState description={error} onRetry={() => void generate()} />
                </div>
              )}
            </div>

            {/* --------------------------- Result --------------------------- */}
            {plan === null ? (
              <EmptyState
                title="Ready when you are"
                description="Pick a role and horizon, then generate. Your plan appears here as a week-by-week timeline."
                icon={Map}
              />
            ) : (
              <motion.div
                initial={{ opacity: 0, y: 10 }}
                animate={{ opacity: 1, y: 0 }}
                className="space-y-8"
              >
                {/* Typo tolerance — tell the user their role was corrected. */}
                {plan.typedRole && plan.typedRole !== plan.targetRole && (
                  <div className="flex items-start gap-2 rounded-xl border border-primary/20 bg-primary/5 px-4 py-3 text-sm text-foreground/80">
                    <Sparkles className="mt-0.5 h-4 w-4 shrink-0 text-primary" />
                    <span>
                      You typed <span className="font-semibold">“{plan.typedRole}”</span> — planning
                      for <span className="font-semibold text-primary">“{plan.targetRole}”</span>{" "}
                      instead.
                    </span>
                  </div>
                )}

                {/* Phase track */}
                <div className="glass rounded-2xl p-5">
                  <div className="flex items-center justify-between text-xs text-muted-foreground">
                    <span className="font-semibold uppercase tracking-wide text-foreground/60">
                      Phase map
                    </span>
                    <span className="inline-flex items-center gap-1">
                      <CalendarRange className="h-3.5 w-3.5" />
                      {plan.horizon} weeks
                    </span>
                  </div>
                  <div className="mt-3 flex w-full overflow-hidden rounded-xl border border-border/60">
                    {plan.phases.map((p, i) => (
                      <div
                        key={p.title + p.weekStart}
                        className="px-3 py-2"
                        style={{
                          width: `${(p.milestones.length / plan.horizon) * 100}%`,
                          background: `oklch(0.7 0.15 ${155 + i * 45} / 0.08)`,
                        }}
                      >
                        <div className="truncate text-xs font-semibold">{p.title}</div>
                        <div className="text-[11px] text-muted-foreground">
                          Wk {p.weekStart}–{p.weekEnd}
                        </div>
                      </div>
                    ))}
                  </div>
                </div>

                {/* Summary + focus skills */}
                <div className="glass rounded-2xl p-6">
                  <p className="text-sm leading-relaxed text-foreground/85">{plan.summary}</p>
                  {plan.targetSkills.length > 0 && (
                    <div className="mt-4">
                      <div className="flex items-center gap-1.5 text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                        <Target className="h-3.5 w-3.5" /> Plan focus skills
                      </div>
                      <div className="mt-2 flex flex-wrap gap-1.5">
                        {plan.targetSkills.map((s) => (
                          <span
                            key={s}
                            className="rounded-full bg-primary/10 px-2.5 py-1 text-[11px] font-medium text-primary"
                          >
                            {s}
                          </span>
                        ))}
                      </div>
                    </div>
                  )}
                </div>

                {/* Timeline */}
                {plan.phases.map((phase, phaseIndex) => (
                  <section key={phase.title} className="glass rounded-2xl p-6">
                    <div className="flex items-center gap-2">
                      <span className="flex h-8 w-8 items-center justify-center rounded-xl bg-primary/10 text-primary">
                        <Flag className="h-4 w-4" />
                      </span>
                      <div>
                        <h3 className="text-base font-semibold">{phase.title}</h3>
                        <p className="text-xs text-muted-foreground">{phase.description}</p>
                      </div>
                      <span className="ml-auto rounded-full border border-border bg-card/50 px-2.5 py-1 text-[11px] font-medium text-muted-foreground">
                        Weeks {phase.weekStart}–{phase.weekEnd}
                      </span>
                    </div>

                    <div className="relative mt-5 ml-3 border-l border-border/60 pl-6">
                      {phase.milestones.map((m, i) => (
                        <motion.div
                          key={m.week}
                          initial={{ opacity: 0, x: 8 }}
                          animate={{ opacity: 1, x: 0 }}
                          transition={{ delay: phaseIndex * 0.08 + i * 0.05 }}
                          className="relative pb-5 last:pb-0"
                        >
                          <span className="absolute -left-[33px] flex h-6 w-6 items-center justify-center rounded-full border border-border bg-card text-[10px] font-bold text-foreground/70">
                            {m.week}
                          </span>
                          <div className="rounded-xl border border-border/60 bg-card/40 p-4">
                            <h4 className="text-sm font-semibold">{m.title}</h4>
                            <p className="mt-1 text-sm text-muted-foreground">{m.focus}</p>
                            {m.skills.length > 0 && (
                              <div className="mt-3 flex flex-wrap gap-1.5">
                                {m.skills.map((s) => (
                                  <span
                                    key={s}
                                    className="rounded-full bg-sky-500/10 px-2 py-0.5 text-[11px] font-medium text-sky-500"
                                  >
                                    {s}
                                  </span>
                                ))}
                              </div>
                            )}
                            {m.deliverable && (
                              <div className="mt-3 flex items-start gap-1.5 border-t border-border/40 pt-3 text-xs text-foreground/80">
                                <CheckCircle2 className="mt-0.5 h-3.5 w-3.5 shrink-0 text-emerald-500" />
                                {m.deliverable}
                              </div>
                            )}
                          </div>
                        </motion.div>
                      ))}
                    </div>
                  </section>
                ))}
              </motion.div>
            )}
          </div>
        )}
      </AppShell>
    </RoleGate>
  );
}
